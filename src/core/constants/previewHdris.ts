import { resolveEnvUrl } from '@/core/assets/assetUrls';
import { createCatalog, withDefault } from '@/core/assets/catalog';
import type { DefaultedCatalog } from '@/core/assets/catalog';
import { assetLabel } from '@/core/assets/labels';
import type {
  PreviewHdri,
  PreviewHdriFormat,
} from '@/core/models/previewHdri';

/**
 * Authored record for one environment.
 *
 * `sourcePath` is the raw panorama that produced the baked `.env`. It is
 * explicit rather than derived because the source filename does not always
 * match the catalog id (e.g. `mossy_forest_2k.hdr` -> `mossy-forest`).
 */
interface PreviewHdriRecord {
  readonly id: string;
  /** Repo-relative path under `src/assets` to the baked `.env`. */
  readonly path: string;
  readonly format: PreviewHdriFormat;
  /** Repo-relative path under `src/assets` to the source panorama. */
  readonly sourcePath?: string;
}

/**
 * Environments available in the scene viewer.
 *
 * The baked `.env` is what the app loads. The raw panoramas are listed here as
 * bake inputs, but only `bakeEnv.ts` may resolve them, through the bake-only
 * `.hdr` module, so they never enter the application bundle.
 */
const records: readonly PreviewHdriRecord[] = [
  {
    id: 'wooden-studio-17',
    path: 'hdri/env/wooden-studio-17.env',
    format: 'env',
    sourcePath: 'hdri/wooden_studio_17_2k.hdr',
  },
  {
    id: 'peppermint-powerplant',
    path: 'hdri/env/peppermint-powerplant.env',
    format: 'env',
    sourcePath: 'hdri/peppermint_powerplant_2k.hdr',
  },
  {
    id: 'pergola-walkway',
    path: 'hdri/env/pergola-walkway.env',
    format: 'env',
    sourcePath: 'hdri/pergola_walkway_2k.hdr',
  },
  {
    id: 'qwantani-sunrise',
    path: 'hdri/env/qwantani-sunrise.env',
    format: 'env',
    sourcePath: 'hdri/qwantani_sunrise_2k.hdr',
  },
  {
    id: 'mossy-forest',
    path: 'hdri/env/mossy-forest.env',
    format: 'env',
    sourcePath: 'hdri/mossy_forest_2k.hdr',
  },
];

const entries: readonly PreviewHdri[] = records.map((record) => ({
  id: record.id,
  label: assetLabel('hdris', record.id),
  url: resolveEnvUrl(record.path),
  format: record.format,
}));

/** Viewer environments; `default` is the explicitly declared `hdri` role. */
export const previewHdris: DefaultedCatalog<PreviewHdri> = withDefault(
  'previewHdris',
  createCatalog('previewHdris', entries, { hdri: 'wooden-studio-17' }),
);

/** The subset of catalog entries that can be regenerated by `bake:env`. */
export interface HdriBakeSource {
  readonly id: string;
  readonly sourcePath: string;
}

export const hdriBakeSources: readonly HdriBakeSource[] = records.flatMap(
  (record) =>
    record.sourcePath === undefined
      ? []
      : [{ id: record.id, sourcePath: record.sourcePath }],
);

/** `.env` filename produced for an environment id. */
export function envFileNameFor(id: string): string {
  return `${id}.env`;
}

export function findPreviewHdri(id: string): PreviewHdri | undefined {
  return previewHdris.find(id);
}
