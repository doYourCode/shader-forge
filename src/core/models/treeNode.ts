import type {
  ContentDifficulty,
  ContentEditor,
} from '@/core/content/contentMetadata';

export interface ITreeNode {
  /** Unique ID (used for selection, routing, etc.) */
  id: string;
  /** Label shown in the tree */
  label: string;
  /** Optional child nodes — recursive */
  children?: ITreeNode[];
  /** Payload for leaves; content body for articles/docs */
  content?: string;
  /** Optional external link (opens in new tab) */
  href?: string;
  /** One-line summary, shown in search results and the content header. */
  description?: string;
  /** Lesson difficulty; `null`/absent for reference pages. */
  difficulty?: ContentDifficulty | null;
  /** Section id, used to label cross-section search results. */
  section?: string;
  /** Order within the section, used by the learning path. */
  order?: number | null;
  /** Slug of a lesson that should be read first. */
  prerequisites?: readonly string[];
  /** Editor this page can open. */
  editor?: ContentEditor | null;
  /** Bundled example id loaded by the editor callout. */
  example?: string | null;
  /** Whether the page offers the print layout. */
  printable?: boolean;
  /** Generated by a build step (see `npm run docs:abi`). */
  generated?: boolean;
}
